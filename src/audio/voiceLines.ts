import { STRINGS, type Txt } from '../i18n/strings';
import { LEVELS } from '../levels/levels';

export interface VoiceLine {
  id: string;
  txt: Txt;
}

/** Every line the game speaks, with the id that names its recording (`<id>.mp3`). */
export function voiceLines(): { general: VoiceLine[]; levels: VoiceLine[] } {
  const general = Object.entries(STRINGS)
    .filter(([key]) => key.startsWith('say') || key === 'gameTitle')
    .map(([id, txt]) => ({ id, txt }));
  const levels = LEVELS.map((l) => ({ id: `${l.id}-intro`, txt: l.intro }));
  return { general, levels };
}

/** The contents of docs/voice-lines.md. */
export function voiceLinesMarkdown(): string {
  const { general, levels } = voiceLines();
  const esc = (s: string) => s.replace(/\|/g, '\\|');
  const table = (lines: VoiceLine[]) =>
    ['| File | Dutch (record this) | English (for reference) |', '|---|---|---|']
      .concat(lines.map((l) => `| \`${l.id}.mp3\` | ${esc(l.txt.nl)} | ${esc(l.txt.en)} |`))
      .join('\n');
  return `# Voice lines

<!-- Generated by \`npm run voice-lines\`. Don't edit by hand: change the strings or levels and regenerate. -->

The game speaks these lines. Until a recording exists, the browser's Dutch text-to-speech reads the line instead.

## How to add your own recordings

1. Record each line in Dutch. A phone voice-memo app is fine. Speak slowly and cheerfully.
2. Save each one as an **.mp3** with the file name from the table, for example \`w1-l1-intro.mp3\`.
3. Put the files in \`public/voice/nl/\`, commit and push. The game uses a recording automatically when it finds one.

Tips: trim the silence at the start and end, and keep the volume about the same for every line.

## General lines

${table(general)}

## Level introductions

${table(levels)}
`;
}
